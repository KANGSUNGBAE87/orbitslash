import { createHash } from "node:crypto";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const rootDirectory = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const coreDirectory = resolve(rootDirectory, "shared/ranked-core");
const generatedDirectory = resolve(rootDirectory, "supabase/functions/_shared/ranked-core");
const sharedIndexPath = resolve(coreDirectory, "index.ts");
const generatedEntryPath = resolve(rootDirectory, "supabase/functions/_shared/orbitslash-ranked-core.generated.ts");
const checkOnly = process.argv.slice(2).includes("--check");
const coreModules = ["types.ts", "rules.ts", "spawn.ts", "score.ts", "replay.ts", "index.ts"];
const rankedDataFiles = [
  "src/data/enemies.json",
  "src/data/difficulty.json",
  "src/data/orbits.json",
  "src/data/waves.json",
  "src/data/scoring.json",
  "src/data/skills.json",
];
const rankedRuntimeSourceFiles = ["src/game/coords.ts", "src/game/BossDefinitions.ts"];

function normalizeLineEndings(source) {
  return source.replace(/\r\n?/g, "\n");
}

function sourcePathLabel(sourcePath) {
  return relative(rootDirectory, sourcePath).replaceAll("\\", "/");
}

function normalizeIndexHash(source) {
  const normalized = source.replace(
    /export const RANKED_CORE_RULES_HASH = "(?:[a-f0-9]{64}|__RANKED_CORE_RULES_HASH__)" as const;/,
    'export const RANKED_CORE_RULES_HASH = "__RANKED_CORE_RULES_HASH__" as const;',
  );
  if (!normalized.includes("__RANKED_CORE_RULES_HASH__")) {
    throw new Error("shared/ranked-core/index.ts must export a generated RANKED_CORE_RULES_HASH string literal.");
  }
  return normalized;
}

function withHash(normalizedIndex, hash) {
  return normalizedIndex.replace("__RANKED_CORE_RULES_HASH__", hash);
}

function readSchemaVersion(source) {
  const match = source.match(/export const RANKED_CORE_SCHEMA_VERSION = (\d+) as const;/);
  if (!match?.[1]) throw new Error("shared/ranked-core/types.ts must export a numeric RANKED_CORE_SCHEMA_VERSION.");
  return match[1];
}

function createHashInput(schemaVersion, sources) {
  return [
    "orbitslash-ranked-core",
    `schema-version:${schemaVersion}`,
    ...sources.map(({ path, source }) => `path:${path}\n${source}`),
  ].join("\n---\n");
}

/** Deno requires explicit local extensions. This is a module-copy transform, not concatenation. */
function denoModuleSource(source) {
  return source.replace(/(from\s+["']\.\/[A-Za-z0-9_-]+)(["'])/g, "$1.ts$2");
}

function generatedEntry(schemaVersion, hash) {
  return [
    "// Generated by scripts/generate-ranked-edge-core.mjs. Do not edit manually.",
    'export * from "./ranked-core/index.ts";',
    `export const RANKED_CORE_SCHEMA_VERSION = ${schemaVersion} as const;`,
    `export const RANKED_CORE_RULES_HASH = "${hash}" as const;`,
    "",
  ].join("\n");
}

function exportedNumericConstant(source, name) {
  const match = source.match(new RegExp(`export const ${name} = ([0-9]+(?:\\.[0-9]+)?);`));
  if (!match?.[1]) throw new Error(`src/game/coords.ts must export numeric ${name}.`);
  return Number(match[1]);
}

function balancedLiteral(source, startAt, label) {
  const assignment = source.indexOf("=", startAt);
  const literalOffset = source.slice(assignment + 1).search(/[\[{]/);
  const start = assignment < 0 || literalOffset < 0 ? -1 : assignment + 1 + literalOffset;
  if (start < 0) throw new Error(`${label} must assign an object or array literal.`);
  const openings = { "{": "}", "[": "]" };
  const stack = [];
  for (let index = start; index < source.length; index += 1) {
    const character = source[index];
    if (character === "{" || character === "[") stack.push(openings[character]);
    if (character === "}" || character === "]") {
      if (stack.pop() !== character) throw new Error(`${label} has mismatched literal delimiters.`);
      if (stack.length === 0) return source.slice(start, index + 1);
    }
  }
  throw new Error(`${label} has an unclosed literal.`);
}

function generatedBossDefinitions(source) {
  const defaultPhasesAt = source.indexOf("const DEFAULT_PHASES");
  const definitionsAt = source.indexOf("export const BOSS_DEFINITIONS");
  if (defaultPhasesAt < 0 || definitionsAt < 0) {
    throw new Error("src/game/BossDefinitions.ts must export BOSS_DEFINITIONS and DEFAULT_PHASES.");
  }
  const defaultPhases = balancedLiteral(source, defaultPhasesAt, "DEFAULT_PHASES");
  const definitions = balancedLiteral(source, definitionsAt, "BOSS_DEFINITIONS");
  // This snapshot is data-only: the controlled source uses DEFAULT_PHASES as its sole local reference.
  return Function(`"use strict"; return (${definitions.replaceAll("DEFAULT_PHASES", `(${defaultPhases})`)});`)();
}

function generatedRulesData(dataSources, runtimeSources) {
  const [enemies, difficulty, orbits, waves, scoring, skills] = dataSources.map((source) => JSON.stringify(JSON.parse(source), null, 2));
  const [coordsSource, bossDefinitionsSource] = runtimeSources;
  const earthCenterX = exportedNumericConstant(coordsSource, "EARTH_CENTER_X");
  const earthCenterY = exportedNumericConstant(coordsSource, "EARTH_CENTER_Y");
  const earthGameplayRadius = exportedNumericConstant(coordsSource, "EARTH_GAMEPLAY_RADIUS");
  const bossDefinitions = JSON.stringify(generatedBossDefinitions(bossDefinitionsSource), null, 2);
  return [
    "// Generated from src/data ranked rules by scripts/generate-ranked-edge-core.mjs. Do not edit manually.",
    "export const RANKED_CORE_RULES = {",
    `  enemies: ${enemies},`,
    `  difficulty: ${difficulty},`,
    `  orbits: (${orbits}).profiles,`,
    `  waves: ${waves},`,
    `  scoring: ${scoring},`,
    `  skills: ${skills},`,
    "  ranked: {",
    `    earthCenterX: ${earthCenterX},`,
    `    earthCenterY: ${earthCenterY},`,
    `    earthGameplayRadius: ${earthGameplayRadius},`,
    "    topHudSafeY: 370,",
    "    startVisualRadiusSafeScale: 0.7,",
    "    rankedSpawnIntervalMultiplier: 0.9,",
    "    periodicBossEveryMs: 75000,",
    '    bossEnemyType: "eclipse_core",',
    "    liveSegmentMinLengthPx: 24,",
    "    normalSlashHitInflatePx: 12,",
    "    solarLanceHitInflatePx: 30,",
    "    scoreSafetyRatio: 1.08,",
    "    scoreSafetyFlat: 2000,",
    "    skillGaugeSafety: 120,",
    "    skillCooldownSafetyCount: 1,",
    "  },",
    "} as const;",
    "",
    "// Generated from src/game/BossDefinitions.ts; Edge replay rules must not duplicate boss weak-point data.",
    `export const RANKED_BOSS_DEFINITIONS = ${bossDefinitions} as const;`,
    "",
  ].join("\n");
}

async function readIfPresent(path) {
  try {
    return await readFile(path, "utf8");
  } catch (error) {
    if (error && typeof error === "object" && "code" in error && error.code === "ENOENT") return undefined;
    throw error;
  }
}

const corePaths = coreModules.map((file) => resolve(coreDirectory, file));
const dataPaths = rankedDataFiles.map((file) => resolve(rootDirectory, file));
const runtimeSourcePaths = rankedRuntimeSourceFiles.map((file) => resolve(rootDirectory, file));
const rawCoreSources = await Promise.all(corePaths.map((path) => readFile(path, "utf8")));
const rawDataSources = await Promise.all(dataPaths.map((path) => readFile(path, "utf8")));
const rawRuntimeSources = await Promise.all(runtimeSourcePaths.map((path) => readFile(path, "utf8")));
const sourceByPath = new Map(corePaths.map((path, index) => [path, normalizeLineEndings(rawCoreSources[index])])) ;
const normalizedIndex = normalizeIndexHash(sourceByPath.get(sharedIndexPath));
sourceByPath.set(sharedIndexPath, normalizedIndex);
const schemaVersion = readSchemaVersion(sourceByPath.get(resolve(coreDirectory, "types.ts")));
const sources = [
  ...corePaths.map((path) => ({ path: sourcePathLabel(path), source: sourceByPath.get(path) })),
  ...dataPaths.map((path, index) => ({ path: sourcePathLabel(path), source: normalizeLineEndings(rawDataSources[index]) })),
  ...runtimeSourcePaths.map((path, index) => ({ path: sourcePathLabel(path), source: normalizeLineEndings(rawRuntimeSources[index]) })),
];
const rulesHash = createHash("sha256").update(createHashInput(schemaVersion, sources)).digest("hex");
const expectedSharedIndex = withHash(normalizedIndex, rulesHash);
const expectedGeneratedModules = new Map(corePaths.map((path) => {
  const source = path === sharedIndexPath ? expectedSharedIndex : sourceByPath.get(path);
  return [resolve(generatedDirectory, relative(coreDirectory, path)), denoModuleSource(source)];
}));
expectedGeneratedModules.set(resolve(generatedDirectory, "data.ts"), generatedRulesData(rawDataSources.map(normalizeLineEndings), rawRuntimeSources.map(normalizeLineEndings)));
const expectedGeneratedEntry = generatedEntry(schemaVersion, rulesHash);

const actualSharedIndex = normalizeLineEndings(await readFile(sharedIndexPath, "utf8"));
const actualGeneratedEntry = await readIfPresent(generatedEntryPath);
const generatedChecks = await Promise.all([...expectedGeneratedModules.entries()].map(async ([path, expected]) => ({
  expected,
  actual: await readIfPresent(path),
})));
const drifted = actualSharedIndex !== expectedSharedIndex ||
  normalizeLineEndings(actualGeneratedEntry ?? "") !== expectedGeneratedEntry ||
  generatedChecks.some(({ expected, actual }) => normalizeLineEndings(actual ?? "") !== expected);

if (checkOnly) {
  if (drifted) {
    process.stderr.write("Ranked core generated artifact drifted. Run: node scripts/generate-ranked-edge-core.mjs\n");
    process.exitCode = 1;
  }
} else {
  await writeFile(sharedIndexPath, expectedSharedIndex, "utf8");
  await mkdir(generatedDirectory, { recursive: true });
  await Promise.all([...expectedGeneratedModules.entries()].map(async ([path, source]) => {
    await mkdir(dirname(path), { recursive: true });
    await writeFile(path, source, "utf8");
  }));
  await writeFile(generatedEntryPath, expectedGeneratedEntry, "utf8");
}
